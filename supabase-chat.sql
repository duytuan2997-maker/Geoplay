create table if not exists public.chat_messages (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    username text not null check (length(username) between 1 and 32),
    avatar text check (
        avatar is null or (
            length(avatar) <= 140000
            and avatar ~ '^data:image/(png|jpeg|webp);base64,[A-Za-z0-9+/]+={0,2}$'
        )
    ),
    content text not null check (length(btrim(content)) between 1 and 500),
    created_at timestamptz not null default now()
);

alter table public.chat_messages add column if not exists avatar text
    check (
        avatar is null or (
            length(avatar) <= 140000
            and avatar ~ '^data:image/(png|jpeg|webp);base64,[A-Za-z0-9+/]+={0,2}$'
        )
    );

update public.chat_messages as messages
set avatar = users.raw_user_meta_data ->> 'avatar'
from auth.users as users
where messages.user_id = users.id
    and messages.avatar is null
    and length(users.raw_user_meta_data ->> 'avatar') <= 140000
    and users.raw_user_meta_data ->> 'avatar' ~
        '^data:image/(png|jpeg|webp);base64,[A-Za-z0-9+/]+={0,2}$';

create index if not exists chat_messages_created_at
    on public.chat_messages (created_at desc);

alter table public.chat_messages enable row level security;

grant select, insert on public.chat_messages to authenticated;

drop policy if exists "Authenticated users can read chat messages"
    on public.chat_messages;
create policy "Authenticated users can read chat messages"
    on public.chat_messages for select
    to authenticated
    using (true);

drop policy if exists "Users can send chat messages as themselves"
    on public.chat_messages;
create policy "Users can send chat messages as themselves"
    on public.chat_messages for insert
    to authenticated
    with check (
        auth.uid() = user_id
        and username = coalesce(
            nullif(auth.jwt() -> 'user_metadata' ->> 'username', ''),
            split_part(auth.jwt() ->> 'email', '@', 1),
            'Học viên'
        )
    );
